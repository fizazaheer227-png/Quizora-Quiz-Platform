/**
 * Returns a randomized quiz question list based on category, difficulty, and count.
 * Also shuffles the options order so answers don't stay in the same slot.
 */
export function getQuizQuestions(
  category: CategoryId,
  difficulty: Difficulty,
  count: number
): Question[] {
  // First filter questions for the given category
  let categoryQuestions = QUESTION_BANK.filter((q) => q.category === category);

  // Try to prioritize matching difficulty, but allow fallback if count > difficulty count
  const matchingDiff = categoryQuestions.filter((q) => q.difficulty === difficulty);
  const otherDiff = categoryQuestions.filter((q) => q.difficulty !== difficulty);

  // Shuffle both arrays using Fisher-Yates
  const shuffledMatching = shuffleArray([...matchingDiff]);
  const shuffledOther = shuffleArray([...otherDiff]);

  const pool = [...shuffledMatching, ...shuffledOther];
  const selected = pool.slice(0, Math.min(count, pool.length));

  // Now randomize options for each selected question
  return selected.map((q) => {
    const originalOptions = q.options.map((opt, idx) => ({
      text: opt,
      isCorrect: idx === q.correctAnswerIndex,
    }));
    const shuffledOptions = shuffleArray([...originalOptions]);
    const newCorrectIndex = shuffledOptions.findIndex((opt) => opt.isCorrect);

    return {
      ...q,
      options: shuffledOptions.map((opt) => opt.text),
      correctAnswerIndex: newCorrectIndex,
    };
  });
}

function shuffleArray<T>(array: T[]): T[] {
  const result = [...array];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}
